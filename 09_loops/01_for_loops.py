#Print table of 5(I method)
for i in range(1, 11):
    print(5*(i))

#Print table of 5(II method)
for i in range(1, 11):
    print("5 X ",i, " = ", 5*(i))

#Print table of 5(III method)
for i in range(1, 11):
    print("5 X ",i, " = ", 5*i)